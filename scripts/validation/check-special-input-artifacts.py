"""Verify already-built local archives against the shared resource manifest; no install/download."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile
import zipfile


def digest(data):
    return hashlib.sha256(data).hexdigest()


def check(args):
    repo = Path(__file__).resolve().parents[2]
    manifest = []
    for line in (repo / "expressions/bundle-files.tsv").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            source, destination = line.split("\t")
            manifest.append((source, destination))
    reports = []
    for kind, archive, prefix in [("windows-portable", args.portable, "current/"),
                                  ("windows-package", args.package, "lib/app/"),
                                  ("android-apk", args.apk, "assets/")]:
        path = Path(archive).resolve()
        with zipfile.ZipFile(path) as zip_file:
            entries = []
            for source, destination in manifest:
                name = prefix + "expressions/" + destination
                data = zip_file.read(name)
                expected = (repo / "expressions" / source).read_bytes()
                assert data == expected, (kind, name)
                entries.append(dict(path=name, bytes=len(data), sha256=digest(data)))
            native = []
            if kind == "android-apk":
                for abi, target, machine in [("arm64-v8a", "aarch64-linux-android", 183),
                                             ("x86_64", "x86_64-linux-android", 62)]:
                    name = f"lib/{abi}/libmywubi_android.so"
                    data = zip_file.read(name)
                    assert data[:5] == b"\x7fELF\x02" and struct.unpack_from("<H", data, 18)[0] == machine
                    source = repo / "target" / target / "release/libmywubi_android.so"
                    # AGP strips symbols before packaging; independently replay that
                    # transformation instead of comparing only two build intermediates.
                    with tempfile.TemporaryDirectory(prefix="mywubi-strip-") as temporary:
                        stripped = Path(temporary) / source.name
                        subprocess.run([args.llvm_strip, "--strip-unneeded", "-o",
                                        str(stripped), str(source)], check=True)
                        assert data == stripped.read_bytes(), (kind, name, "stripped Cargo output")
                    native.append(dict(path=name, bytes=len(data), sha256=digest(data),
                                       cargo_sha256=digest(source.read_bytes()),
                                       transformation="llvm-strip --strip-unneeded"))
            else:
                for name in ["settings.exe", "im_engine.dll"]:
                    data = zip_file.read(prefix + name)
                    assert data == (repo / "target/release" / name).read_bytes(), (kind, name)
                    native.append(dict(path=prefix + name, bytes=len(data), sha256=digest(data)))
            reports.append(dict(kind=kind, path=str(path), bytes=path.stat().st_size,
                                sha256=digest(path.read_bytes()), resources=entries, native=native))
    installer = Path(args.installer).resolve()
    reports.append(dict(kind="windows-installer", path=str(installer), bytes=installer.stat().st_size,
                        sha256=digest(installer.read_bytes()),
                        scope="Container generated by the same local vpk pack; installer was not executed"))
    test_apk = Path(args.test_apk).resolve()
    reports.append(dict(kind="android-test-apk", path=str(test_apk), bytes=test_apk.stat().st_size,
                        sha256=digest(test_apk.read_bytes()), scope="Compiled device tests; not installed or run"))
    report = dict(scope="Local archive contents only; no fresh installation, upgrade, UI or actual host acceptance",
                  source_commit=args.source_commit, resources_per_archive=len(manifest), downloads=0,
                  llvm_strip=str(Path(args.llvm_strip).resolve()), artifacts=reports)
    Path(args.output).write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Verified {len(manifest)} resource/license files in each of three archives, Windows binaries and both Android ABIs")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    for option in ["portable", "package", "apk", "installer", "test-apk", "source-commit", "llvm-strip", "output"]:
        parser.add_argument("--" + option, required=True)
    check(parser.parse_args())
